"""Deploy the hot-data Worker (T042) with account values from the ignored .env (D180).

The committed worker/wrangler.toml stays disabled (no database ID, workers.dev off, gate blocked).
This script writes the git-ignored worker/wrangler.deploy.toml with the real D1 binding, the
workers.dev route and CAPABILITY_GATE = "verified_free_no_card" (owner-confirmed free plan with
no card, 12 Nov 2026), then runs the pinned Wrangler. The upload-signing key goes in as a Worker
secret over stdin; no token, ID or key is printed or committed.
Usage: .venv/Scripts/python scripts/deploy_worker.py [--dry-run]
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NODE = ROOT / ".tools/node/node-v22.16.0-win-x64"
WRANGLER = ROOT / "worker/node_modules/wrangler/bin/wrangler.js"
DEPLOY = ROOT / "worker/wrangler.deploy.toml"
NEEDED = (
    "CLOUDFLARE_API_TOKEN",
    "CLOUDFLARE_ACCOUNT_ID",
    "CLOUDFLARE_D1_DATABASE_ID",
    "ATLAS_INGEST_HMAC_KEY",
)


def env_file() -> dict[str, str]:
    pairs = {}
    for line in (ROOT / ".env").read_text("utf-8-sig").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            pairs[k.strip()] = v.strip()
    missing = [k for k in NEEDED if not pairs.get(k)]
    if missing:
        sys.exit(f"missing in .env: {missing}")
    return pairs


def deploy_config(base: str, database_id: str) -> str:
    for old, new in (
        ("workers_dev = false", "workers_dev = true"),
        ('CAPABILITY_GATE = "blocked"', 'CAPABILITY_GATE = "verified_free_no_card"'),
    ):
        if old not in base:
            sys.exit(f"worker/wrangler.toml changed: {old!r} not found")
        base = base.replace(old, new)
    return (
        "# Generated by scripts/deploy_worker.py from .env; git-ignored, never commit.\n"
        + base
        + '\n[[d1_databases]]\nbinding = "DB"\ndatabase_name = "monsoon-atlas-hot"\n'
        + f'database_id = "{database_id}"\n'
    )


def main(argv: list[str]) -> int:
    pairs = env_file()
    DEPLOY.write_text(
        deploy_config(
            (ROOT / "worker/wrangler.toml").read_text("utf-8"), pairs["CLOUDFLARE_D1_DATABASE_ID"]
        ),
        encoding="utf-8",
        newline="\n",
    )
    env = os.environ | {
        "CLOUDFLARE_API_TOKEN": pairs["CLOUDFLARE_API_TOKEN"],
        "CLOUDFLARE_ACCOUNT_ID": pairs["CLOUDFLARE_ACCOUNT_ID"],
        "WRANGLER_SEND_METRICS": "false",
        "TEMP": str(ROOT / ".cache/tmp"),
        "TMP": str(ROOT / ".cache/tmp"),
        "XDG_CONFIG_HOME": str(ROOT / ".cache/wrangler"),
        "XDG_CACHE_HOME": str(ROOT / ".cache"),
        "npm_config_cache": str(ROOT / ".cache/npm"),
        "PATH": str(NODE) + os.pathsep + os.environ.get("PATH", ""),
    }
    base = [str(NODE / "node.exe"), str(WRANGLER)]
    cwd = ROOT / "worker"
    if "--dry-run" in argv:
        cmd = [
            *base,
            "deploy",
            "--config",
            DEPLOY.name,
            "--dry-run",
            "--outdir",
            "../.cache/worker-dry",
        ]
        return subprocess.run(cmd, cwd=cwd, env=env).returncode
    code = subprocess.run([*base, "deploy", "--config", DEPLOY.name], cwd=cwd, env=env).returncode
    if code:
        return code
    put = [*base, "secret", "put", "ATLAS_INGEST_HMAC_KEY", "--config", DEPLOY.name]
    return subprocess.run(
        put, cwd=cwd, env=env, input=pairs["ATLAS_INGEST_HMAC_KEY"] + "\n", text=True
    ).returncode


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
